# ОБРАБОТКА СООБЩЕНИЙ
# ==================================================

async def handle_message(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    try:
        logger.info("========================================")
        logger.info("[СООБЩЕНИЕ] Получено новое обновление")

        if update.message is None:
            logger.warning("[СООБЩЕНИЕ] update.message отсутствует")
            return

        if update.message.text is None:
            logger.warning("[СООБЩЕНИЕ] В сообщении нет текста")
            return

        user_text = update.message.text

        logger.info(
            "[СООБЩЕНИЕ] Получен текст. Длина: %s символов",
            len(user_text)
        )

        logger.info("[GROQ] Отправляем запрос к AI")

        response = await asyncio.to_thread(
            client.chat.completions.create,
            model="openai/gpt-oss-20b",
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT
                },
                {
                    "role": "user",
                    "content": user_text
                }
            ],
            temperature=0.3
        )

        logger.info("[GROQ] Ответ от AI получен")

        answer = response.choices[0].message.content

        if not answer:
            logger.warning("[GROQ] AI вернул пустой ответ")

            answer = (
                "Не получилось сформировать ответ. "
                "Попробуйте задать вопрос ещё раз."
            )

        logger.info(
            "[GROQ] Ответ сформирован. Длина: %s символов",
            len(answer)
        )

        logger.info("[TELEGRAM] Отправляем ответ пользователю")

        await update.message.reply_text(answer)

        logger.info("[TELEGRAM] Ответ успешно отправлен")
        logger.info("[СООБЩЕНИЕ] Обработка завершена")

    except Exception as error:

        logger.exception(
            "[ОШИБКА] Ошибка при обработке сообщения: %s",
            error
        )

        try:
            if update.message:
                await update.message.reply_text(
                    "Сейчас не получилось обработать сообщение. "
                    "Попробуйте ещё раз немного позже."
                )

                logger.info("[TELEGRAM] Сообщение об ошибке отправлено")

        except Exception:
            logger.exception(
                "[ОШИБКА] Не удалось отправить сообщение об ошибке"
            )


# ==================================================
# ОБЩИЙ ОБРАБОТЧИК ОШИБОК TELEGRAM
# ==================================================

async def error_handler(
    update: object,
    context: ContextTypes.DEFAULT_TYPE
):

    logger.error(
        "[TELEGRAM] Необработанная ошибка:",
        exc_info=context.error
    )


# ==================================================
# ЗАПУСК БОТА
# ==================================================

def main():

    try:
        logger.info("========================================")
        logger.info("ЗАПУСК AI-АДМИНИСТРАТОРА")

        logger.info("[9] Создаём Telegram Application")

        app = Application.builder().token(TELEGRAM_TOKEN).build()

        logger.info("[10] Telegram Application создан")

        logger.info("[11] Регистрируем обработчик сообщений")

        app.add_handler(
            MessageHandler(
                filters.TEXT & ~filters.COMMAND,
                handle_message
            )
        )

        logger.info("[12] Регистрируем обработчик ошибок")

        app.add_error_handler(error_handler)

        logger.info("[13] Все обработчики зарегистрированы")

        print("\nAI администратор запущен!")
        print("Ожидаю сообщения в Telegram...")
        print("Логи сохраняются в bot.log\n")

        logger.info("[14] Запускаем Telegram polling")

        app.run_polling()

        logger.info("[15] Telegram polling завершён")

    except KeyboardInterrupt:
        logger.warning("Бот остановлен пользователем")

    except Exception:
        logger.exception("КРИТИЧЕСКАЯ ОШИБКА ПРИ ЗАПУСКЕ БОТА")

        print("\nПроизошла критическая ошибка. Подробности в bot.log")

        input("Нажмите Enter для выхода...")


# ==================================================
# ТОЧКА ВХОДА
# ==================================================

if __name__ == "__main__":

    logger.info("Запуск main.py")

    main()
